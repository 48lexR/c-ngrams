#!/usr/bin/env python

import random
from typing import Optional

from database_manager import DatabaseManager
from tokenizer import IDENTIFIER

# Names substituted for <ID> placeholders when writing C-token output
_NAMES = ["a", "b", "c", "i", "j", "n", "x", "y", "buf", "len", "count", "tmp", "node", "ptr"]

# Spacing rules for joining C tokens back into source
_NO_SPACE_BEFORE = {";", ",", ")", "]", ".", "->", "++", "--"}
_NO_SPACE_AFTER = {"(", "[", ".", "->"}


class Generator:
    """Samples token sequences from an n-gram model stored in the database."""

    def __init__(self, db: DatabaseManager, n: int, system: str = "", seed: Optional[int] = None):
        if not db.has_table(n, system):
            raise ValueError(
                f"No {system or 'char'} {n}-gram model in {db.fname}. Train one first."
            )
        self.db = db
        self.n = n
        self.system = system
        self.rng = random.Random(seed)
        self._contexts, self._weights = db.contexts(n, system)

    def _random_context(self) -> list[str]:
        return list(self.rng.choices(self._contexts, self._weights)[0])

    def generate(self, length: int) -> list[str]:
        """Generate `length` tokens."""
        tokens = self._random_context()
        while len(tokens) < length:
            context = tuple(tokens[-(self.n - 1):]) if self.n > 1 else ()
            options = self.db.next_tokens(context, self.n, self.system)
            if not options:
                # Dead end: this context only appeared at the end of a
                # training file. Restart from a random context.
                tokens.extend(self._random_context())
                continue
            choices, probs = zip(*options)
            tokens.append(self.rng.choices(choices, probs)[0])
        return tokens[:length]

    def to_source(self, tokens: list[str]) -> str:
        """Turn generated tokens back into source text."""
        if self.system == "":
            return ''.join(tokens)
        return self._format_c(tokens)

    def _format_c(self, tokens: list[str]) -> str:
        lines: list[str] = []
        line = ""
        depth = 0
        prev = None

        def end_line():
            nonlocal line, prev
            if line:
                lines.append("    " * depth + line)
            line = ""
            prev = None

        for tok in tokens:
            if tok == IDENTIFIER:
                tok = self.rng.choice(_NAMES)

            if tok.startswith("#") and len(tok) > 1:   # preprocessor directive
                end_line()
                lines.append(tok)
                continue

            if tok == "}":
                end_line()
                depth = max(depth - 1, 0)

            if prev is None or tok in _NO_SPACE_BEFORE or prev in _NO_SPACE_AFTER:
                line += tok
            else:
                line += " " + tok
            prev = tok

            if tok == "{":
                end_line()
                depth += 1
            elif tok in (";", "}"):
                end_line()

        end_line()
        return "\n".join(lines) + "\n"

    def write(self, path: str, length: int) -> str:
        """Generate `length` tokens and write them to `path`. Returns the text."""
        source = self.to_source(self.generate(length))
        header = f"/* Generated by c-ngrams: {self.system or 'char'} {self.n}-gram model */\n"
        with open(path, "w") as f:
            f.write(header + source)
        return source
